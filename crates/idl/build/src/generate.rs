//! Deterministic Rust binding generation from a resolved IDL graph.

use std::fmt;

use neocogi_idl::{
    AbiType, Callable, Declaration, DeclarationKind, EnumNames, EnumRepr, Event, Method, NamedType, Receiver, ResolvedDeclaration, ResolvedModule,
    ResolvedModules, Threading, VariantFields,
};
use proc_macro2::{Ident, Literal, Span, TokenStream};
use quote::quote;

use crate::EVENT_BINDING_API_VERSION;

/// Failure to select a module or lower one validated IDL construct to Rust.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GenerateError {
    /// Concrete unsupported or internally inconsistent generation condition.
    message: String,
}

impl GenerateError {
    /// Creates one generator diagnostic without exposing mutable error state.
    fn new(message: impl Into<String>) -> Self {
        Self { message: message.into() }
    }
}

impl fmt::Display for GenerateError {
    /// Writes the generator's actionable diagnostic.
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.message)
    }
}

impl std::error::Error for GenerateError {}

/// Generates complete Rust bindings for one module in a resolved graph.
///
/// The output contains ABI layouts, typed calls, description marker constants,
/// and already-computed declaration signatures as fixed byte literals. Runtime
/// descriptions and plugin implementations are deliberately absent; those
/// belong to the native contract artifact and implementation crates respectively.
pub fn generate_rust(graph: &ResolvedModules, module_name: &str) -> Result<String, GenerateError> {
    let module = graph
        .module(module_name)
        .ok_or_else(|| GenerateError::new(format!("resolved graph has no module {module_name:?}")))?;
    let imports = generate_imports(module)?;
    let event_alloc = module
        .source
        .declarations
        .iter()
        .any(|item| matches!(item.kind, DeclarationKind::Event(_)))
        .then(|| quote! { extern crate alloc; });
    let event_binding_check = module.source.declarations.iter().any(uses_event_support).then(|| {
        let version = Literal::u32_unsuffixed(EVENT_BINDING_API_VERSION);
        quote! {
            /// Rejects a transport support crate built for a different compiler event API.
            /// NCIDL fingerprints identify wire contracts, not Rust adapter semantics.
            const _: () = assert!(::neocogi_com_events::EVENT_BINDING_API_VERSION == #version);
        }
    });
    let declarations = module
        .source
        .declarations
        .iter()
        .enumerate()
        .map(|(index, declaration)| generate_declaration(graph, module, declaration, index))
        .collect::<Result<Vec<_>, _>>()?;
    let module_id = guid_literal(module.module_id);
    let fingerprint = module.abi_fingerprint.iter().copied();
    let module_name = Literal::string(module_name);
    // The COM event transport module is seeded by the runtime rather than
    // exported from a separately linked native description library.
    let native_reference = (module.source.name.to_string() != neocogi_idl::COM_EVENTS_MODULE_NAME).then(|| {
        let link_name = Literal::string(&native_link_name(module));
        let getter_name = Literal::string(&native_getter_name(module));
        quote! {
            unsafe extern "C" {
                #[link_name = #getter_name]
                fn __nc_get_contract_module_description() -> *const ::neocogi_com::NcContractModuleDescription;
            }

            /// Exact native linker name containing this module's description.
            pub const NATIVE_LINK_NAME: &str = #link_name;

            /// Verified reference to the fingerprint-qualified native description.
            pub const MODULE: ::neocogi_com::NcContractModuleReference = ::neocogi_com::NcContractModuleReference {
                module_id: MODULE_ID,
                abi_fingerprint: ::neocogi_com::NcContractFingerprint::new(ABI_FINGERPRINT),
                get: Some(__nc_get_contract_module_description),
            };
        }
    });

    let tokens = quote! {
        // This file is generated by neocogi-idl-build. Edit the .ncidl source.
        #event_alloc
        #imports
        #event_binding_check

        /// Stable logical identity of this generated contract module.
        pub const MODULE_ID: ::neocogi_com::NcGuid = #module_id;

        /// Transitive canonical ABI fingerprint of this generated module.
        pub const ABI_FINGERPRINT: [u8; 32] = [#(#fingerprint),*];

        /// Exact dotted module name derived from the normalized IDL path.
        pub const MODULE_NAME: &str = #module_name;

        #native_reference

    };
    let mut source = String::from("// This file is generated by neocogi-idl-build. Edit the .ncidl source.\n\n");
    source.push_str(&format_rust(tokens)?);
    for declaration in declarations {
        // Keep declarations visibly separated so generated files remain useful
        // during diagnostics, reviews, and editor navigation.
        source.push('\n');
        source.push_str(&declaration);
    }
    Ok(source)
}

/// Identifies declarations whose generated bodies require the COM event API.
/// An event definition needs a typed adapter; an event port needs a generated
/// registration connector even when its sink is imported from another module.
fn uses_event_support(declaration: &Declaration) -> bool {
    match &declaration.kind {
        DeclarationKind::Event(_) => true,
        DeclarationKind::Interface(interface) => interface.callables.iter().any(|callable| matches!(callable, Callable::EventPort(_))),
        DeclarationKind::Class(class) => class.callables.iter().any(|callable| matches!(callable, Callable::EventPort(_))),
        DeclarationKind::Factory(factory) => factory.callables.iter().any(|callable| matches!(callable, Callable::EventPort(_))),
        DeclarationKind::Struct(_) | DeclarationKind::Enum(_) | DeclarationKind::BitEnum(_) => false,
    }
}

/// Returns the fingerprint-qualified native linker name for one module.
pub(crate) fn native_link_name(module: &ResolvedModule) -> String {
    format!("nc_contract_{}_{}", module.source.name.to_string().replace('.', "_"), module.fingerprint_hex())
}

/// Returns the exported getter name owned by one exact module revision.
pub(crate) fn native_getter_name(module: &ResolvedModule) -> String {
    format!("{}_get_v1", native_link_name(module))
}

/// Generates explicit imports from conventionally named contract crates.
fn generate_imports(module: &ResolvedModule) -> Result<TokenStream, GenerateError> {
    let imports = module.source.imports.iter().map(|import| {
        let crate_ident = contract_crate_ident(&import.module)?;
        let names = import.names.iter().map(|name| rust_ident(name)).collect::<Result<Vec<_>, _>>()?;
        Ok(quote! { pub use ::#crate_ident::{#(#names),*}; })
    });
    let imports = imports.collect::<Result<Vec<_>, GenerateError>>()?;
    Ok(quote! { #(#imports)* })
}

/// Generates one public declaration from its resolved source-order identity.
fn generate_declaration(graph: &ResolvedModules, module: &ResolvedModule, declaration: &Declaration, source_index: usize) -> Result<String, GenerateError> {
    let declaration_docs = docs(&declaration.docs);
    let name = rust_ident(&declaration.name)?;
    let identity = module
        .declarations
        .get(source_index)
        .ok_or_else(|| GenerateError::new("resolved declaration order does not match its source module"))?;
    // One contract module remains the compatibility unit, but the resolver
    // folds the declaration ID into each signature so typed metadata can still
    // distinguish two aggregates from the same exact module revision.
    let assigned_signature = signature_literal(identity.abi_signature);
    let id = Literal::string(&identity.id.to_string());
    let qualified_name = Literal::string(&identity.qualified_name);
    let version = identity.version;
    match &declaration.kind {
        DeclarationKind::Struct(record) => {
            let com_struct = match (record.deserialize, record.deserialize_default, record.deserialize_sequence) {
                (false, false, false) => quote! { #[::neocogi_com::com_struct(assigned_signature = #assigned_signature)] },
                (true, false, false) => quote! { #[::neocogi_com::com_struct(deserialize, assigned_signature = #assigned_signature)] },
                (true, true, false) => quote! { #[::neocogi_com::com_struct(deserialize, default, assigned_signature = #assigned_signature)] },
                (true, false, true) => quote! { #[::neocogi_com::com_struct(deserialize, sequence, assigned_signature = #assigned_signature)] },
                _ => return Err(GenerateError::new("resolved struct contains an invalid deserialize policy")),
            };
            let fields = record
                .fields
                .iter()
                .map(|field| {
                    let docs = docs(&field.docs);
                    let field_name = rust_ident(&field.name)?;
                    let ty = value_type(graph, module, &field.ty)?;
                    Ok(quote! { #docs pub #field_name: #ty, })
                })
                .collect::<Result<Vec<_>, GenerateError>>()?;
            format_rust(quote! {
                #com_struct
                #[derive(Debug, PartialEq)]
                #declaration_docs
                pub struct #name { #(#fields)* }
            })
        }
        DeclarationKind::Enum(enumeration) => {
            let repr = enum_repr(enumeration.repr);
            let has_payload = enum_has_payload(enumeration);
            let value_names = enumeration
                .variants
                .iter()
                .map(|variant| rust_ident(&variant.name))
                .collect::<Result<Vec<_>, _>>()?;
            let dense_members = if enumeration.dense {
                let count = enumeration.variants.len();
                let canonical_members = match enumeration.names {
                    Some(EnumNames::SnakeCase) => {
                        let names = enumeration
                            .variants
                            .iter()
                            .map(|variant| Literal::string(&snake_case(&variant.name)))
                            .collect::<Vec<_>>();
                        quote! {
                            /// Canonical names corresponding exactly to [`Self::ALL`].
                            pub const NAMES: [&'static str; Self::COUNT] = [#(#names),*];

                            /// Returns the canonical name, or `None` for an unknown ABI value.
                            pub const fn canonical_name(self) -> Option<&'static str> {
                                let ordinal = self.raw() as usize;
                                if ordinal < Self::COUNT { Some(Self::NAMES[ordinal]) } else { None }
                            }
                        }
                    }
                    None => quote! {},
                };
                quote! {
                    impl #name {
                        /// Number of declared values in this dense IDL domain.
                        pub const COUNT: usize = #count;

                        /// Every declared value in its zero-based discriminant order.
                        pub const ALL: [Self; Self::COUNT] = [#(Self::#value_names),*];

                        #canonical_members
                    }
                }
            } else {
                quote! {}
            };
            let mut previous = -1i64;
            let variants = enumeration
                .variants
                .iter()
                .map(|variant| {
                    let variant_docs = docs(&variant.docs);
                    let variant_name = rust_ident(&variant.name)?;
                    let discriminant = variant.discriminant.unwrap_or(previous + 1);
                    previous = discriminant;
                    if discriminant < 0 {
                        return Err(GenerateError::new(format!(
                            "enum {} uses negative discriminant {discriminant}, which generated tagged enums do not yet support",
                            declaration.name
                        )));
                    }
                    let tag = Literal::u64_unsuffixed(discriminant as u64);
                    let fields = match &variant.fields {
                        VariantFields::Unit => quote! {},
                        VariantFields::Tuple(fields) => {
                            let fields = fields.iter().map(|ty| value_type(graph, module, ty)).collect::<Result<Vec<_>, _>>()?;
                            quote! { (#(#fields),*) }
                        }
                        VariantFields::Named(fields) => {
                            let fields = fields
                                .iter()
                                .map(|field| {
                                    let docs = docs(&field.docs);
                                    let name = rust_ident(&field.name)?;
                                    let ty = value_type(graph, module, &field.ty)?;
                                    Ok(quote! { #docs #name: #ty })
                                })
                                .collect::<Result<Vec<_>, GenerateError>>()?;
                            quote! { { #(#fields),* } }
                        }
                    };
                    if has_payload {
                        Ok(quote! { #[com_tag(#tag)] #variant_docs #variant_name #fields, })
                    } else {
                        Ok(quote! { #variant_docs #variant_name = #tag, })
                    }
                })
                .collect::<Result<Vec<_>, GenerateError>>()?;
            if has_payload {
                format_rust(quote! {
                    #[::neocogi_com::com_enum(tag = #repr, assigned_signature = #assigned_signature)]
                    #[derive(Clone, Copy, Debug, PartialEq)]
                    #declaration_docs
                    pub enum #name { #(#variants)* }
                })
            } else {
                let mut source = format_macro_enum("com_int_enum", "enum", declaration_docs, &name, &repr, &variants)?;
                source.push_str(&format_rust(dense_members)?);
                Ok(source)
            }
        }
        DeclarationKind::BitEnum(bit_enum) => {
            let repr = enum_repr(bit_enum.repr);
            let flags = bit_enum
                .flags
                .iter()
                .map(|flag| {
                    let flag_docs = docs(&flag.docs);
                    let flag_name = rust_ident(&flag.name)?;
                    let value = Literal::u64_unsuffixed(flag.value);
                    Ok(quote! { #flag_docs #flag_name = #value, })
                })
                .collect::<Result<Vec<_>, GenerateError>>()?;
            format_macro_enum("com_bit_enum", "bitenum", declaration_docs, &name, &repr, &flags)
        }
        DeclarationKind::Interface(interface) => {
            let bases = bases(graph, module, &interface.bases)?;
            let methods = callable_methods(graph, module, &interface.callables)?;
            let connectors = event_port_connectors(graph, module, declaration, &interface.callables, Threading::Local)?;
            format_rust(quote! {
                #[::neocogi_com::com_interface(
                    assigned_guid = #id,
                    name = #qualified_name,
                    assigned_signature = #assigned_signature
                )]
                #declaration_docs
                pub trait #name #bases { #(#methods)* }
                #(#connectors)*
            })
        }
        DeclarationKind::Event(event) => generate_event(
            graph,
            module,
            declaration,
            event,
            &declaration_docs,
            &name,
            &id,
            &qualified_name,
            &assigned_signature,
        ),
        DeclarationKind::Class(class) => {
            let bases = bases(graph, module, &class.required_interfaces)?;
            let methods = callable_methods(graph, module, &class.callables)?;
            let threading = threading_ident(class.threading);
            let connectors = event_port_connectors(graph, module, declaration, &class.callables, class.threading)?;
            format_rust(quote! {
                #[::neocogi_com::com_class_description(
                    id = #id,
                    name = #qualified_name,
                    version = #version,
                    threading = #threading,
                    assigned_signature = #assigned_signature
                )]
                #declaration_docs
                pub trait #name #bases { #(#methods)* }
                #(#connectors)*
            })
        }
        DeclarationKind::Factory(factory) => {
            let bases = bases(graph, module, &factory.required_interfaces)?;
            let methods = callable_methods(graph, module, &factory.callables)?;
            let threading = threading_ident(factory.threading);
            let connectors = event_port_connectors(graph, module, declaration, &factory.callables, factory.threading)?;
            format_rust(quote! {
                #[::neocogi_com::com_factory_description(
                    id = #id,
                    name = #qualified_name,
                    version = #version,
                    threading = #threading,
                    assigned_signature = #assigned_signature
                )]
                #declaration_docs
                pub trait #name #bases { #(#methods)* }
                #(#connectors)*
            })
        }
    }
}

/// Emits the sink ABI, one owned native payload sum, its producer delivery,
/// and a concrete typed application adapter from a single NCIDL event family.
/// The generated contract crate depends on `neocogi-com-events` only when it
/// contains events; neither plugin binary shares a Rust callback representation.
fn generate_event(
    graph: &ResolvedModules,
    module: &ResolvedModule,
    declaration: &Declaration,
    event: &Event,
    declaration_docs: &TokenStream,
    name: &Ident,
    id: &Literal,
    qualified_name: &Literal,
    assigned_signature: &Literal,
) -> Result<String, GenerateError> {
    let sink_methods = methods(graph, module, &event.deliveries)?;
    let payload_name = rust_ident(&format!("{}Event", declaration.name))?;
    let adapter_name = rust_ident(&format!("{}EventAdapter", declaration.name))?;
    let sink_abi_name = rust_ident(&format!("{}Abi", declaration.name))?;
    let adapter_factory = rust_ident(&format!("create_{}_event_sink", snake_case(&declaration.name)))?;
    let checked_factory = rust_ident(&format!("create_{}_checked_event_sink", snake_case(&declaration.name)))?;

    let mut variants = Vec::with_capacity(event.deliveries.len());
    let mut producer_arms = Vec::with_capacity(event.deliveries.len());
    let mut adapter_methods = Vec::with_capacity(event.deliveries.len());
    let single = event.deliveries.len() == 1;
    let mut single_fields = Vec::new();
    for delivery in &event.deliveries {
        let variant = rust_ident(&upper_camel_case(&delivery.name))?;
        let method_name = rust_ident(&delivery.name)?;
        let method_docs = docs(&delivery.docs);
        let mut fields = Vec::with_capacity(delivery.parameters.len());
        let mut bindings = Vec::with_capacity(delivery.parameters.len());
        let mut encoded = Vec::with_capacity(delivery.parameters.len());
        let mut parameters = Vec::with_capacity(delivery.parameters.len());
        let mut decoded = Vec::with_capacity(delivery.parameters.len());
        for parameter in &delivery.parameters {
            let field = rust_ident(&parameter.name)?;
            let owned = event_owned_type(graph, module, &parameter.ty)?;
            let input = parameter_type(graph, module, &parameter.ty)?;
            let encode = event_encode(graph, module, &parameter.ty, &field)?;
            let decode = event_decode(graph, module, &parameter.ty, &field)?;
            let field_doc = Literal::string(&format!(" Captured {} value copied at the event boundary.", parameter.name));
            fields.push(quote! { #[doc = #field_doc] #field: #owned, });
            if single {
                single_fields.push(quote! { #[doc = #field_doc] pub #field: #owned, });
            }
            bindings.push(field.clone());
            encoded.push(encode);
            parameters.push(quote! { #field: #input });
            decoded.push(quote! { #field: #decode });
        }
        let variant_doc = Literal::string(&format!(" Immutable {} event snapshot.", delivery.name));
        if fields.is_empty() {
            let captured = if single {
                quote! { #payload_name }
            } else {
                quote! { #payload_name::#variant }
            };
            variants.push(quote! { #[doc = #variant_doc] #variant, });
            producer_arms.push(if single {
                quote! { Self => sink.#method_name() }
            } else {
                quote! { Self::#variant => sink.#method_name() }
            });
            adapter_methods.push(quote! {
                #method_docs fn #method_name(&self) -> Result<(), ::neocogi_com::NcStatus> {
                    let event = #captured;
                    if let Some(validate) = self.validate { validate(&event)?; }
                    self.delivery.deliver(event)
                }
            });
        } else {
            let captured = if single {
                quote! { #payload_name }
            } else {
                quote! { #payload_name::#variant }
            };
            variants.push(quote! { #[doc = #variant_doc] #variant { #(#fields)* }, });
            producer_arms.push(if single {
                quote! { Self { #(#bindings),* } => sink.#method_name(#(#encoded),*) }
            } else {
                quote! { Self::#variant { #(#bindings),* } => sink.#method_name(#(#encoded),*) }
            });
            adapter_methods.push(quote! {
                #method_docs fn #method_name(&self, #(#parameters),*) -> Result<(), ::neocogi_com::NcStatus> {
                    let event = #captured { #(#decoded),* };
                    if let Some(validate) = self.validate { validate(&event)?; }
                    self.delivery.deliver(event)
                }
            });
        }
    }

    let payload_declaration = if single {
        let can_derive = event.deliveries[0].parameters.iter().all(|parameter| {
            !matches!(&parameter.ty, AbiType::Borrowed(referent) if !matches!(referent.as_ref(), AbiType::Named(name) if name.segments.as_slice() == ["str"]))
        });
        let derives = can_derive.then(|| quote! { #[derive(Clone, Debug, PartialEq)] });
        if single_fields.is_empty() {
            quote! {
                #derives
                /// One captured unit event with no invented sentinel payload.
                pub struct #payload_name;
            }
        } else {
            quote! {
                #derives
                /// One owned native event snapshot generated from its NCIDL delivery.
                pub struct #payload_name { #(#single_fields)* }
            }
        }
    } else {
        quote! {
            /// Owned native sum of the distinct NCIDL delivery facts.
            pub enum #payload_name { #(#variants)* }
        }
    };

    format_rust(quote! {
        #[::neocogi_com::com_interface(
            assigned_guid = #id,
            name = #qualified_name,
            assigned_signature = #assigned_signature
        )]
        #declaration_docs
        pub trait #name { #(#sink_methods)* }

        #payload_declaration

        impl ::neocogi_com_events::EventPayload for #payload_name {
            type Sink = #sink_abi_name;

            /// Replays the captured snapshot through its one generated sink interface.
            fn deliver(&self, sink: ::neocogi_com::ComRef<'_, Self::Sink>) -> Result<(), ::neocogi_com::NcStatus> {
                match self { #(#producer_arms),* }
            }
        }

        #[::neocogi_com::com_object(interfaces(#name))]
        /// Concrete local application adapter with the exact state and handler types.
        struct #adapter_name<State: 'static, Handler: ::neocogi_com_events::EventHandler<State, #payload_name> + 'static> {
            /// Application-owned typed delivery; the producer retains only a COM lease.
            delivery: ::neocogi_com_events::EventDelivery<State, Handler>,
            /// Concrete semantic check runs after decoding but before state or handler borrowing.
            validate: Option<fn(&#payload_name) -> Result<(), ::neocogi_com::NcStatus>>,
        }

        impl<State: 'static, Handler: ::neocogi_com_events::EventHandler<State, #payload_name> + 'static> #name for #adapter_name<State, Handler> {
            #(#adapter_methods)*
        }

        /// Creates an application-local typed sink for this generated event family.
        /// Register its resulting producer lease with `EventSession::register`.
        pub fn #adapter_factory<State: 'static, Handler: ::neocogi_com_events::EventHandler<State, #payload_name> + 'static>(
            session: &::neocogi_com_events::EventSession<State>,
            handler: Handler,
        ) -> Result<::neocogi_com::ComPtr<#sink_abi_name>, ::neocogi_com::NcStatus> {
            #adapter_name::from_value(#adapter_name { delivery: session.delivery(handler), validate: None }).query()
        }

        /// Creates a generated sink with one typed domain check before application-state borrowing.
        /// The checker cannot capture runtime state or cross the COM ABI; it sees only the owned fact.
        pub fn #checked_factory<State: 'static, Handler: ::neocogi_com_events::EventHandler<State, #payload_name> + 'static>(
            session: &::neocogi_com_events::EventSession<State>,
            handler: Handler,
            validate: fn(&#payload_name) -> Result<(), ::neocogi_com::NcStatus>,
        ) -> Result<::neocogi_com::ComPtr<#sink_abi_name>, ::neocogi_com::NcStatus> {
            #adapter_name::from_value(#adapter_name { delivery: session.delivery(handler), validate: Some(validate) }).query()
        }
    })
}

/// Selects owned native snapshot storage for one event-delivery input type.
fn event_owned_type(graph: &ResolvedModules, module: &ResolvedModule, ty: &AbiType) -> Result<TokenStream, GenerateError> {
    match ty {
        AbiType::Scalar(_) | AbiType::Array { .. } => value_type(graph, module, ty),
        AbiType::Named(name) => {
            let resolved = resolve(graph, module, name)?;
            named_rust_type(module, resolved, false)
        }
        AbiType::Borrowed(referent) => match referent.as_ref() {
            AbiType::Named(name) if name.segments.as_slice() == ["str"] => Ok(quote! { ::alloc::string::String }),
            AbiType::Named(name) => object_reference_type(graph, module, name, true),
            _ => Err(GenerateError::new("event borrow cannot be captured as an owned snapshot")),
        },
        AbiType::Slice(element) => {
            let element = value_type(graph, module, element)?;
            Ok(quote! { ::alloc::vec::Vec<#element> })
        }
        AbiType::OutputSlice(_) | AbiType::Option(_) | AbiType::Unit | AbiType::String => {
            Err(GenerateError::new("event input has no owned snapshot representation"))
        }
    }
}

/// Encodes one borrowed native payload field into its concrete sink call.
fn event_encode(graph: &ResolvedModules, module: &ResolvedModule, ty: &AbiType, field: &Ident) -> Result<TokenStream, GenerateError> {
    match ty {
        AbiType::Scalar(_) | AbiType::Array { .. } => Ok(quote! { *#field }),
        AbiType::Named(name) => {
            let resolved = resolve(graph, module, name)?;
            if matches!(&resolved.declaration.kind, DeclarationKind::Enum(value) if enum_has_payload(value)) {
                Ok(quote! { (*#field).into() })
            } else {
                Ok(quote! { *#field })
            }
        }
        AbiType::Borrowed(referent) => match referent.as_ref() {
            AbiType::Named(name) if name.segments.as_slice() == ["str"] => Ok(quote! { ::neocogi_com::NcCopyFromBufferOffset::new(0, #field.as_bytes()) }),
            AbiType::Named(_) => Ok(quote! { #field.as_com_ref() }),
            _ => Err(GenerateError::new("event borrow has no sink encoding")),
        },
        AbiType::Slice(_) => Ok(quote! { ::neocogi_com::NcCopyFromBufferOffset::new(0, #field.as_slice()) }),
        _ => Err(GenerateError::new("event input has no sink encoding")),
    }
}

/// Copies or validates one foreign sink argument before calling application code.
fn event_decode(graph: &ResolvedModules, module: &ResolvedModule, ty: &AbiType, field: &Ident) -> Result<TokenStream, GenerateError> {
    match ty {
        AbiType::Scalar(_) | AbiType::Array { .. } => Ok(quote! { #field }),
        AbiType::Named(name) => {
            let resolved = resolve(graph, module, name)?;
            if matches!(&resolved.declaration.kind, DeclarationKind::Enum(value) if enum_has_payload(value)) {
                let value = named_rust_type(module, resolved, false)?;
                Ok(quote! { #value::try_from(#field).map_err(|_| ::neocogi_com::NC_E_INVALID_ARG)? })
            } else {
                Ok(quote! { #field })
            }
        }
        AbiType::Borrowed(referent) => match referent.as_ref() {
            AbiType::Named(name) if name.segments.as_slice() == ["str"] => Ok(quote! { ::neocogi_com_events::copy_text(#field)? }),
            AbiType::Named(_) => Ok(quote! { #field.add_ref() }),
            _ => Err(GenerateError::new("event borrow has no owned decoding")),
        },
        AbiType::Slice(_) => Ok(quote! { ::neocogi_com_events::copy_slice(#field)? }),
        _ => Err(GenerateError::new("event input has no owned decoding")),
    }
}

/// Converts a validated snake-case delivery method into its payload variant.
fn upper_camel_case(value: &str) -> String {
    value
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut characters = part.chars();
            match characters.next() {
                Some(first) => first.to_uppercase().collect::<String>() + characters.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

/// Formats ordinary generated Rust syntax with stable, human-readable layout.
fn format_rust(tokens: TokenStream) -> Result<String, GenerateError> {
    // `TokenStream::to_string` is intended for diagnostics rather than source
    // generation: it collapses layout and exposes doc comments as `#[doc]`.
    // Parsing gives the source printer enough syntax to choose conventional
    // whitespace and documentation-comment notation.
    let syntax = syn::parse2::<syn::File>(tokens).map_err(|error| GenerateError::new(format!("generated invalid Rust syntax: {error}")))?;
    Ok(prettyplease::unparse(&syntax))
}

/// Formats the Rust-like body accepted by one declarative COM enum macro.
fn format_macro_enum(
    macro_name: &str,
    keyword: &str,
    declaration_docs: TokenStream,
    name: &Ident,
    repr: &TokenStream,
    members: &[TokenStream],
) -> Result<String, GenerateError> {
    // Pretty-printers intentionally treat arbitrary macro bodies as opaque.
    // Format an equivalent, valid Rust enum first, then restore the small
    // `enum Name: Repr` / `bitenum Name: Repr` grammar owned by our macros.
    let formatted = format_rust(quote! {
        #declaration_docs
        #[repr(#repr)]
        pub enum #name { #(#members)* }
    })?;
    let repr_attribute = format!("#[repr({repr})]");
    let rust_declaration = format!("pub enum {name} {{");
    let macro_declaration = format!("pub {keyword} {name}: {repr} {{");
    let mut found_declaration = false;
    let mut source = format!("::neocogi_com::{macro_name}! {{\n");

    for line in formatted.lines() {
        // The representation is expressed after the name in the macro grammar,
        // so its temporary standard-Rust attribute must not remain in the body.
        if line == repr_attribute {
            continue;
        }
        source.push_str("    ");
        if line == rust_declaration {
            source.push_str(&macro_declaration);
            found_declaration = true;
        } else {
            source.push_str(line);
        }
        source.push('\n');
    }
    if !found_declaration {
        return Err(GenerateError::new(format!("formatted enum {name} lost its generated declaration")));
    }
    source.push_str("}\n");
    Ok(source)
}

/// Converts one Rust-like variant identifier into a stable snake-case name.
fn snake_case(value: &str) -> String {
    let characters = value.chars().collect::<Vec<_>>();
    let mut result = String::new();
    for (index, character) in characters.iter().copied().enumerate() {
        if character.is_uppercase() {
            let previous = index.checked_sub(1).and_then(|previous| characters.get(previous)).copied();
            let next = characters.get(index + 1).copied();
            if !result.is_empty()
                && !result.ends_with('_')
                && (previous.is_some_and(|value| value.is_lowercase() || value.is_numeric()) || next.is_some_and(char::is_lowercase))
            {
                result.push('_');
            }
            result.extend(character.to_lowercase());
        } else {
            result.push(character);
        }
    }
    result
}

/// Generates a Rust supertrait suffix from IDL required interfaces.
fn bases(graph: &ResolvedModules, module: &ResolvedModule, values: &[NamedType]) -> Result<TokenStream, GenerateError> {
    if values.is_empty() {
        return Ok(quote! {});
    }
    let values = values
        .iter()
        .map(|value| {
            let resolved = resolve(graph, module, value)?;
            named_rust_type(module, resolved, false)
        })
        .collect::<Result<Vec<_>, _>>()?;
    Ok(quote! { : #(#values)+* })
}

/// Generates callable methods with explicit `NcStatus` error types.
fn methods(graph: &ResolvedModules, module: &ResolvedModule, values: &[Method]) -> Result<Vec<TokenStream>, GenerateError> {
    values
        .iter()
        .map(|method| {
            let docs = docs(&method.docs);
            let name = rust_ident(&method.name)?;
            let receiver = match method.receiver {
                Receiver::Shared => quote! { &self },
                Receiver::Mutable => quote! { &mut self },
            };
            let parameters = method
                .parameters
                .iter()
                .map(|parameter| {
                    let name = rust_ident(&parameter.name)?;
                    let ty = parameter_type(graph, module, &parameter.ty)?;
                    Ok(quote! { #name: #ty })
                })
                .collect::<Result<Vec<_>, GenerateError>>()?;
            let output = output_type(graph, module, &method.output)?;
            Ok(quote! {
                #docs fn #name(#receiver, #(#parameters),*) -> Result<#output, ::neocogi_com::NcStatus>;
            })
        })
        .collect()
}

/// Emits ordinary methods and first-class event ports in their normative order.
fn callable_methods(graph: &ResolvedModules, module: &ResolvedModule, values: &[Callable]) -> Result<Vec<TokenStream>, GenerateError> {
    let mut generated = Vec::with_capacity(values.len());
    for callable in values {
        let method = match callable {
            Callable::Method(method) => std::borrow::Cow::Borrowed(method),
            Callable::EventPort(port) => std::borrow::Cow::Owned(port.signature()),
        };
        generated.extend(methods(graph, module, std::slice::from_ref(method.as_ref()))?);
    }
    Ok(generated)
}

/// Generates one application registration transaction for every declared event port.
/// The helper is source-specific because a port is an actual COM method on one
/// interface identity; it never guesses a widget capability or retains the
/// borrowed source beyond the synchronous subscription call.
fn event_port_connectors(
    graph: &ResolvedModules,
    module: &ResolvedModule,
    source: &Declaration,
    values: &[Callable],
    threading: Threading,
) -> Result<Vec<TokenStream>, GenerateError> {
    let source_abi = rust_ident(&format!("{}Abi", source.name))?;
    let mode = matches!(threading, Threading::Shared).then(|| quote! { , ::neocogi_com::ThreadSafe });
    let mut connectors = Vec::new();
    for callable in values {
        let Callable::EventPort(port) = callable else { continue };
        let sink = resolve(graph, module, &port.sink)?;
        let sink_event = rust_ident(&format!("{}Event", sink.declaration.name))?;
        let factory = rust_ident(&format!("create_{}_event_sink", snake_case(&sink.declaration.name)))?;
        let checked_factory = rust_ident(&format!("create_{}_checked_event_sink", snake_case(&sink.declaration.name)))?;
        let (payload, sink_factory, checked_sink_factory) = if sink.module.source.name == module.source.name {
            (quote! { #sink_event }, quote! { #factory }, quote! { #checked_factory })
        } else {
            let crate_name = contract_crate_ident(&sink.module.source.name.to_string())?;
            (
                quote! { ::#crate_name::#sink_event },
                quote! { ::#crate_name::#factory },
                quote! { ::#crate_name::#checked_factory },
            )
        };
        let port_name = rust_ident(&port.name)?;
        let connected_source = match port.receiver {
            Receiver::Shared => quote! { source },
            Receiver::Mutable => quote! { mut source },
        };
        // Each port owns a distinct local operation type. Its borrowed source
        // and optional validator are visible fields, never closure captures.
        let connector_name = rust_ident(&format!("{}{}EventConnector", source.name, upper_camel_case(&port.name)))?;
        let check_name = rust_ident(&format!("{}DomainCheck", connector_name))?;
        let helper = rust_ident(&format!("connect_{}_{}", snake_case(&source.name), port.name))?;
        let checked_helper = rust_ident(&format!("connect_{}_{}_checked", snake_case(&source.name), port.name))?;
        let port_docs = docs(&port.docs);
        connectors.push(quote! {
            /// Capture-free semantic check for this port's concrete owned event payload.
            type #check_name = fn(&#payload) -> Result<(), ::neocogi_com::NcStatus>;

            /// Local subscription operation generated for this exact source event port.
            /// Consumed synchronously; neither its borrowed source nor this operation
            /// is retained by the session or crosses the COM ABI.
            struct #connector_name<'source> {
                /// Exact source projection borrowed until the foreign subscription returns.
                source: ::neocogi_com::ComRef<'source, #source_abi #mode>,
                /// Existing capture-free domain check installed on the resulting local sink.
                validate: Option<#check_name>,
            }

            impl<State: 'static, Handler: ::neocogi_com_events::EventHandler<State, #payload> + 'static>
                ::neocogi_com_events::EventConnector<State, Handler> for #connector_name<'_>
            {
                /// Creates the typed sink only after the session claims registration.
                /// Selects the existing plain or checked sink policy, then connects
                /// the exact source port without retaining its borrowed projection.
                fn connect(
                    self,
                    session: &::neocogi_com_events::EventSession<State>,
                    handler: Handler,
                ) -> Result<::neocogi_com::ComPtr<::neocogi_com_events::IEventSubscriptionAbi>, ::neocogi_com::NcStatus> {
                    // Both policies use the same port and ordered registration protocol.
                    let sink = match self.validate {
                        Some(validate) => #checked_sink_factory(session, handler, validate)?,
                        None => #sink_factory(session, handler)?,
                    };
                    // Only mutable ports require an exclusive source projection.
                    let #connected_source = self.source;
                    source.#port_name(sink.as_com_ref())
                }
            }

            #port_docs
            /// Registers the generated sink and source lease in one ordered session transaction.
            /// A failed foreign subscription restores registration order without claiming a handler.
            pub fn #helper<State: 'static, Handler: ::neocogi_com_events::EventHandler<State, #payload> + 'static>(
                session: &::neocogi_com_events::EventSession<State>,
                source: ::neocogi_com::ComRef<'_, #source_abi #mode>,
                handler: Handler,
            ) -> Result<::neocogi_com::ComPtr<::neocogi_com_events::IEventSubscriptionAbi>, ::neocogi_com::NcStatus> {
                session.register(handler, #connector_name { source, validate: None })
            }

            /// Registers this port with an application-local semantic validator.
            /// Validation runs after ABI decoding and before the state/handler borrow.
            pub fn #checked_helper<State: 'static, Handler: ::neocogi_com_events::EventHandler<State, #payload> + 'static>(
                session: &::neocogi_com_events::EventSession<State>,
                source: ::neocogi_com::ComRef<'_, #source_abi #mode>,
                handler: Handler,
                validate: fn(&#payload) -> Result<(), ::neocogi_com::NcStatus>,
            ) -> Result<::neocogi_com::ComPtr<::neocogi_com_events::IEventSubscriptionAbi>, ::neocogi_com::NcStatus> {
                session.register(handler, #connector_name { source, validate: Some(validate) })
            }
        });
    }
    Ok(connectors)
}

/// Lowers one copied aggregate field or payload type.
fn value_type(graph: &ResolvedModules, module: &ResolvedModule, ty: &AbiType) -> Result<TokenStream, GenerateError> {
    match ty {
        AbiType::Scalar(name) => scalar(name),
        AbiType::Named(name) => {
            let resolved = resolve(graph, module, name)?;
            match resolved.declaration.kind {
                DeclarationKind::Struct(_) | DeclarationKind::BitEnum(_) => named_rust_type(module, resolved, false),
                DeclarationKind::Enum(_) => named_rust_type(module, resolved, true),
                _ => Err(GenerateError::new(format!("{} is not a copied value declaration", name.rust_path()))),
            }
        }
        AbiType::Array { element, len } => {
            let element = value_type(graph, module, element)?;
            let len = Literal::u32_unsuffixed(*len);
            Ok(quote! { [#element; #len] })
        }
        AbiType::Option(_) => Err(GenerateError::new(
            "Option<T> binding generation requires the dedicated optional-value ABI layout",
        )),
        _ => Err(GenerateError::new("borrowed, string, and unit types cannot occupy copied aggregate storage")),
    }
}

/// Lowers one method input according to its explicit IDL ownership form.
fn parameter_type(graph: &ResolvedModules, module: &ResolvedModule, ty: &AbiType) -> Result<TokenStream, GenerateError> {
    match ty {
        AbiType::Scalar(_) | AbiType::Named(_) | AbiType::Array { .. } => {
            if let AbiType::Named(name) = ty {
                let resolved = resolve(graph, module, name)?;
                if !matches!(
                    resolved.declaration.kind,
                    DeclarationKind::Struct(_) | DeclarationKind::Enum(_) | DeclarationKind::BitEnum(_)
                ) {
                    return Err(GenerateError::new(format!("object parameter {} must be borrowed", name.rust_path())));
                }
            }
            value_type(graph, module, ty)
        }
        AbiType::Borrowed(referent) => match referent.as_ref() {
            AbiType::Named(name) if name.segments.as_slice() == ["str"] => Ok(quote! { ::neocogi_com::NcCopyFromBufferOffset<'_, u8> }),
            AbiType::Named(name) => object_reference_type(graph, module, name, false),
            _ => Err(GenerateError::new("IDL borrows support only str and object declarations")),
        },
        AbiType::Slice(element) => {
            let element = value_type(graph, module, element)?;
            Ok(quote! { ::neocogi_com::NcCopyFromBufferOffset<'_, #element> })
        }
        AbiType::OutputSlice(element) => {
            let element = value_type(graph, module, element)?;
            Ok(quote! { ::neocogi_com::NcCopyToBufferOffset<'_, #element> })
        }
        AbiType::Option(_) => Err(GenerateError::new(
            "Option<T> parameter generation requires the dedicated optional-value ABI layout",
        )),
        AbiType::Unit | AbiType::String => Err(GenerateError::new("unit and owned String are not valid method inputs")),
    }
}

/// Lowers one successful method output and its ownership transfer.
fn output_type(graph: &ResolvedModules, module: &ResolvedModule, ty: &AbiType) -> Result<TokenStream, GenerateError> {
    match ty {
        AbiType::Unit => Ok(quote! { () }),
        AbiType::String => Ok(quote! { ::neocogi_com::ComPtr<::neocogi_com::INcStringAbi> }),
        AbiType::Named(name) => {
            let resolved = resolve(graph, module, name)?;
            if matches!(
                resolved.declaration.kind,
                DeclarationKind::Struct(_) | DeclarationKind::Enum(_) | DeclarationKind::BitEnum(_)
            ) {
                value_type(graph, module, ty)
            } else {
                object_reference_type(graph, module, name, true)
            }
        }
        AbiType::Scalar(_) | AbiType::Array { .. } => value_type(graph, module, ty),
        AbiType::Option(_) => Err(GenerateError::new(
            "Option<T> result generation requires the dedicated optional-value ABI layout",
        )),
        AbiType::Borrowed(_) | AbiType::Slice(_) | AbiType::OutputSlice(_) => Err(GenerateError::new("methods cannot return borrowed values")),
    }
}

/// Produces a `ComRef` or `ComPtr` for one interface-like declaration.
fn object_reference_type(graph: &ResolvedModules, module: &ResolvedModule, name: &NamedType, owned: bool) -> Result<TokenStream, GenerateError> {
    let resolved = resolve(graph, module, name)?;
    if matches!(
        resolved.declaration.kind,
        DeclarationKind::Struct(_) | DeclarationKind::Enum(_) | DeclarationKind::BitEnum(_)
    ) {
        return Err(GenerateError::new(format!("{} is a copied value, not an object reference", name.rust_path())));
    }
    let abi = named_rust_type(module, resolved, true)?;
    let threading = match &resolved.declaration.kind {
        DeclarationKind::Class(class) => class.threading,
        DeclarationKind::Factory(factory) => factory.threading,
        DeclarationKind::Interface(_) | DeclarationKind::Event(_) => Threading::Local,
        _ => unreachable!("value declarations were rejected above"),
    };
    let mode = matches!(threading, Threading::Shared).then(|| quote! { , ::neocogi_com::ThreadSafe });
    if owned {
        Ok(quote! { ::neocogi_com::ComPtr<#abi #mode> })
    } else {
        Ok(quote! { ::neocogi_com::ComRef<'_, #abi #mode> })
    }
}

/// Resolves a type through the semantic graph with an internal-invariant error.
fn resolve<'a>(graph: &'a ResolvedModules, module: &ResolvedModule, name: &NamedType) -> Result<ResolvedDeclaration<'a>, GenerateError> {
    graph
        .resolve_declaration(&module.source.name.to_string(), name)
        .ok_or_else(|| GenerateError::new(format!("resolved module {} lost type mapping for {}", module.source.name, name.rust_path())))
}

/// Selects a local/imported Rust type and optionally its generated ABI suffix.
fn named_rust_type(module: &ResolvedModule, resolved: ResolvedDeclaration<'_>, abi_suffix: bool) -> Result<TokenStream, GenerateError> {
    let mut name = resolved.declaration.name.clone();
    if abi_suffix && declaration_has_abi_wrapper(resolved.declaration) {
        name.push_str("Abi");
    }
    let name = rust_ident(&name)?;
    if resolved.module.source.name == module.source.name {
        Ok(quote! { #name })
    } else {
        let crate_ident = contract_crate_ident(&resolved.module.source.name.to_string())?;
        Ok(quote! { ::#crate_ident::#name })
    }
}

/// Returns whether a generated declaration exposes a separate ABI wrapper type.
fn declaration_has_abi_wrapper(declaration: &Declaration) -> bool {
    match &declaration.kind {
        DeclarationKind::Struct(_) | DeclarationKind::BitEnum(_) => false,
        DeclarationKind::Enum(enumeration) => enum_has_payload(enumeration),
        DeclarationKind::Interface(_) | DeclarationKind::Event(_) | DeclarationKind::Class(_) | DeclarationKind::Factory(_) => true,
    }
}

/// Distinguishes tagged sum types from transparent integer enumerations.
fn enum_has_payload(enumeration: &neocogi_idl::Enum) -> bool {
    enumeration.variants.iter().any(|variant| !matches!(variant.fields, VariantFields::Unit))
}

/// Generates doc attributes while preserving authored text exactly.
fn docs(lines: &[String]) -> TokenStream {
    // Rust's canonical doc-comment spelling contains one space after `///`.
    // The leading space in the attribute value lets the syntax-aware printer
    // recover that spelling instead of producing a visually cramped comment.
    let lines = lines.iter().map(|line| Literal::string(&format!(" {line}")));
    quote! { #(#[doc = #lines])* }
}

/// Converts one validated IDL identifier into a Rust token identifier.
fn rust_ident(value: &str) -> Result<Ident, GenerateError> {
    syn::parse_str::<Ident>(value).map_err(|_| GenerateError::new(format!("IDL identifier {value:?} is not a Rust identifier")))
}

/// Derives the conventional Rust crate identifier for an imported module.
fn contract_crate_ident(module: &str) -> Result<Ident, GenerateError> {
    let crate_name = format!("{}_contracts", module.replace('.', "_"));
    rust_ident(&crate_name)
}

/// Emits a field-wise GUID expression independent of host byte order.
fn guid_literal(value: neocogi_com_core::NcGuid) -> TokenStream {
    let (data1, data2, data3, data4) = value.fields();
    quote! { ::neocogi_com::NcGuid::from_fields(#data1, #data2, #data3, [#(#data4),*]) }
}

/// Emits one complete SHA-256 digest as a fixed Rust byte array.
fn signature_literal(value: [u8; 32]) -> Literal {
    Literal::byte_string(&value)
}

/// Converts one enum representation into its Rust fixed-width integer type.
fn enum_repr(value: EnumRepr) -> TokenStream {
    match value {
        EnumRepr::U8 => quote! { u8 },
        EnumRepr::U16 => quote! { u16 },
        EnumRepr::U32 => quote! { u32 },
        EnumRepr::I8 => quote! { i8 },
        EnumRepr::I16 => quote! { i16 },
        EnumRepr::I32 => quote! { i32 },
    }
}

/// Converts an IDL threading capability into the macro's grammar identifier.
fn threading_ident(value: Threading) -> Ident {
    match value {
        Threading::Local => Ident::new("local", Span::call_site()),
        Threading::Shared => Ident::new("shared", Span::call_site()),
    }
}

/// Converts one supported scalar spelling into a Rust type token.
fn scalar(value: &str) -> Result<TokenStream, GenerateError> {
    match value {
        "Status" => Ok(quote! { ::neocogi_com::NcStatus }),
        "bool" | "i8" | "i16" | "i32" | "i64" | "u8" | "u16" | "u32" | "u64" | "f32" | "f64" => {
            let ident = rust_ident(value)?;
            Ok(quote! { #ident })
        }
        _ => Err(GenerateError::new(format!("unsupported scalar type {value:?}"))),
    }
}
